#!/usr/bin/env python3
"""assets.json -> src/art.js

Emits the palette, every sprite and the font as compact JS literals.  The font
is flattened to a '#' mask so the engine can draw text in any colour.

Run build/extract.py first if the sheet has changed; this script only needs the
standard library.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ASSETS = os.path.join(HERE, 'ref', 'assets.json')
OUT = os.path.join(ROOT, 'src', 'art.js')

HEADER = """// GENERATED by build/gen_art.py -- do not edit by hand.
//
// Sprite and font data extracted pixel-for-pixel from a community rip of the
// 1979 Namco Galaxian ROM graphics (build/ref/sprites.png).  Every colour is
// an authentic Namco hardware value.  See README.md for what is original and
// what is reconstructed.
"""


def js_rows(rows):
    return '[' + ','.join('"%s"' % r for r in rows) + ']'


def main():
    with open(ASSETS) as fh:
        a = json.load(fh)

    lines = [HEADER]
    lines.append('const PALETTE = %s;' % json.dumps(a['palette'], sort_keys=True))
    lines.append('')

    lines.append('const ART = {')
    for name in sorted(a['sprites']):
        lines.append('  %s: %s,' % (name, js_rows(a['sprites'][name])))
    lines.append('};')
    lines.append('')

    # font -> '#' mask, drawn in whatever colour the caller asks for
    lines.append('const FONT = {')
    for ch in sorted(a['font']):
        mask = [''.join('#' if c != '.' else '.' for c in row)
                for row in a['font'][ch]]
        key = '"%s"' % ch
        lines.append('  %s: %s,' % (key, js_rows(mask)))
    lines.append('};')
    lines.append('')

    with open(OUT, 'w') as fh:
        fh.write('\n'.join(lines))

    print('wrote', OUT, os.path.getsize(OUT), 'bytes')
    print('  %d sprites, %d glyphs' % (len(a['sprites']), len(a['font'])))


if __name__ == '__main__':
    main()
